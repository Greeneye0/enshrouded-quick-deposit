"""Generates the powrprof.dll forwarding stubs (src/proxy_stubs.asm, src/powrprof.def,
src/proxy_exports.h) from tools/powrprof_exports.txt ("<ordinal> <name>" per line).

Regenerate the export list with:
  dumpbin /exports C:\\Windows\\System32\\powrprof.dll
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
exports = []
for line in (root / "tools" / "powrprof_exports.txt").read_text().splitlines():
    if line.strip():
        ordinal, name = line.split()
        exports.append((int(ordinal), name))

asm = ["; generated by tools/gen_proxy.py - do not edit", "EXTERN g_proxyTargets:QWORD", ".code"]
for i, (_, name) in enumerate(exports):
    asm += [f"{name}_proxy PROC", f"    jmp QWORD PTR [g_proxyTargets + {i * 8}]", f"{name}_proxy ENDP"]
asm.append("END")
(root / "src" / "proxy_stubs.asm").write_text("\n".join(asm) + "\n")

defs = ["; generated by tools/gen_proxy.py - do not edit", "LIBRARY powrprof", "EXPORTS"]
defs += [f"    {name}={name}_proxy @{ordinal}" for ordinal, name in exports]
(root / "src" / "powrprof.def").write_text("\n".join(defs) + "\n")

header = ["// generated by tools/gen_proxy.py - do not edit", "#pragma once",
          f"constexpr int kProxyExportCount = {len(exports)};",
          "static const char* const kProxyExportNames[kProxyExportCount] = {"]
header += [f'    "{name}",' for _, name in exports]
header.append("};")
(root / "src" / "proxy_exports.h").write_text("\n".join(header) + "\n")
print(f"generated {len(exports)} forwarders")
